def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "music"
    )
    os.makedirs(outdir, exist_ok=True)
    if not _have("lame"):
        sys.exit("error: `lame` not found on PATH (needed for MP3 encoding)")

    manifest = {"version": 1, "license": LICENSE, "tracks": []}
    for spec in TRACKS:
        title = spec["title"]
        slug = title.lower().replace(" ", "-")
        wav = os.path.join(outdir, slug + ".wav")
        mp3 = os.path.join(outdir, slug + ".mp3")
        print(f"==> rendering {title} ({spec['bpm']} BPM)…", flush=True)
        write_wav(wav, render_track(spec))
        subprocess.run(
            ["lame", "-V", "4", "--quiet", "--add-id3v2",
             "--tt", title, "--ta", ARTIST, "--tl", ALBUM, wav, mp3],
            check=True,
        )
        os.remove(wav)
        size = os.path.getsize(mp3)
        print(f"    {slug}.mp3  {size // 1024} KB", flush=True)
        manifest["tracks"].append({
            "title": title, "artist": ARTIST, "album": ALBUM,
            "file": slug + ".mp3", "license": LICENSE, "bpm": spec["bpm"],
        })

    with open(os.path.join(outdir, "music.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print(f"done: {len(TRACKS)} tracks + music.json in {outdir}")


def _have(binary):
    from shutil import which

    return which(binary) is not None


if __name__ == "__main__":
    main()
