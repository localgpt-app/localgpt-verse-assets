#!/usr/bin/env python3
"""Generate Reverie's CC0 starter music pack.

These are *original algorithmic compositions* synthesized from scratch —
additive pads, sine sub-bass, plucked bells, optional soft percussion, and a
Schroeder reverb. No sampled, recorded, or copyrighted material is involved,
so the output carries no third-party rights and is released into the public
domain under CC0-1.0. Chord progressions are generic harmonic building blocks
(not copyrightable); every waveform here is generated by this script.

Usage:
    python3 generate_music.py [outdir]     # default: ./music

Requires `lame` on PATH for MP3 encoding + ID3 tags.
"""
import array
import json
import math
import os
import subprocess
import sys

SR = 32000
LUT_N = 4096
SINE = [math.sin(2.0 * math.pi * i / LUT_N) for i in range(LUT_N)]
MASK = LUT_N - 1

ARTIST = "Reverie"
ALBUM = "Starter Worlds"
LICENSE = "CC0-1.0"


# ---------------------------------------------------------------------------
# Pitch helpers
# ---------------------------------------------------------------------------
_NOTE = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def hz(name):
    """Note name like 'C3', 'F#4', 'Bb2' -> frequency in Hz (A4 = 440)."""
    letter = name[0].upper()
    i = 1
    semis = _NOTE[letter]
    if i < len(name) and name[i] in "#b":
        semis += 1 if name[i] == "#" else -1
        i += 1
    octave = int(name[i:])
    midi = semis + (octave + 1) * 12
    return 440.0 * (2.0 ** ((midi - 69) / 12.0))


# ---------------------------------------------------------------------------
# Envelopes (precomputed per event, indexed per sample)
# ---------------------------------------------------------------------------
def ramp_env(n, attack, release):
    """Raised-cosine attack/release window of length n samples."""
    a = max(1, int(attack * SR))
    r = max(1, int(release * SR))
    env = array.array("d", bytes(8 * n))
    for i in range(n):
        if i < a:
            g = 0.5 - 0.5 * math.cos(math.pi * i / a)
        elif i > n - r:
            k = (n - i) / r
            g = 0.5 - 0.5 * math.cos(math.pi * k)
        else:
            g = 1.0
        env[i] = g
    return env


def pluck_env(n, decay):
    """Exponential pluck: instant attack, exp decay over `decay` seconds."""
    env = array.array("d", bytes(8 * n))
    k = 1.0 / (decay * SR)
    for i in range(n):
        env[i] = math.exp(-k * i)
    return env


# ---------------------------------------------------------------------------
# Voices — each adds into stereo buffers L, R
# ---------------------------------------------------------------------------
def add_sine(L, R, start, freq, amp, env, panL, panR, detune=0.0):
    """Add a LUT sine of `freq` Hz into [start, start+len(env)) with `env`."""
    n = len(env)
    total = len(L)
    inc = LUT_N * freq * (2.0 ** (detune / 1200.0)) / SR
    ph = 0.0
    for i in range(n):
        j = start + i
        if j >= total:
            break
        s = SINE[int(ph) & MASK] * amp * env[i]
        L[j] += s * panL
        R[j] += s * panR
        ph += inc


def add_noise(L, R, start, env, amp, seed, panL, panR):
    """Add a short filtered-noise burst (a soft hat)."""
    n = len(env)
    total = len(L)
    x = seed & 0x7FFFFFFF
    prev = 0.0
    for i in range(n):
        j = start + i
        if j >= total:
            break
        x = (1103515245 * x + 12345) & 0x7FFFFFFF
        w = (x / 0x3FFFFFFF) - 1.0
        hp = w - prev  # 1-pole highpass → brighter, hat-like
        prev = w
        s = hp * amp * env[i]
        L[j] += s * panL
        R[j] += s * panR


def add_chord_pad(L, R, start, dur, freqs, amp):
    """A warm two-layer detuned pad holding `freqs` for `dur` seconds."""
    n = int(dur * SR)
    env = ramp_env(n, attack=0.9, release=1.1)
    for f in freqs:
        add_sine(L, R, start, f, amp, env, 0.62, 0.42, detune=-6.0)
        add_sine(L, R, start, f, amp, env, 0.42, 0.62, detune=+6.0)


def add_kick(L, R, start):
    """Sine kick with a fast pitch drop."""
    n = int(0.16 * SR)
    total = len(L)
    ph = 0.0
    for i in range(n):
        j = start + i
        if j >= total:
            break
        t = i / SR
        f = 42.0 + 78.0 * math.exp(-t * 34.0)
        e = math.exp(-t * 16.0)
        s = math.sin(ph) * 0.9 * e
        L[j] += s
        R[j] += s
        ph += 2.0 * math.pi * f / SR


# ---------------------------------------------------------------------------
# Composition
# ---------------------------------------------------------------------------
def render_track(spec):
    """Render one track spec to interleaved 16-bit stereo bytes."""
    bpm = spec["bpm"]
    beat = 60.0 / bpm
    chord_beats = spec.get("chord_beats", 8)
    chord_dur = beat * chord_beats
    prog = spec["prog"]
    loops = spec["loops"]

    total_secs = chord_dur * len(prog) * loops + 2.0
    total = int(total_secs * SR)
    L = array.array("d", bytes(8 * total))
    R = array.array("d", bytes(8 * total))

    rng = spec["seed"]

    def rand():
        nonlocal rng
        rng = (1103515245 * rng + 12345) & 0x7FFFFFFF
        return rng / 0x7FFFFFFF

    t = 0.0
    for _loop in range(loops):
        for chord in prog:
            start = int(t * SR)
            root = hz(chord["bass"])
            pad_freqs = [hz(nm) for nm in chord["pad"]]

            # Sub-bass on the chord root.
            add_sine(
                L, R, start, root, 0.34,
                ramp_env(int(chord_dur * SR), 0.05, 0.4),
                0.5, 0.5,
            )
            # Warm pad.
            add_chord_pad(L, R, start, chord_dur, pad_freqs, spec["pad_amp"])

            # Bell / arp figure on a beat grid.
            steps = int(chord_beats / spec["arp_every"])
            for s in range(steps):
                if rand() > spec["arp_density"]:
                    continue
                bt = t + s * spec["arp_every"] * beat
                bstart = int(bt * SR)
                note = pad_freqs[int(rand() * len(pad_freqs))] * 2.0
                env = pluck_env(int(0.7 * SR), 0.55)
                pan = 0.30 + 0.40 * rand()
                add_sine(L, R, bstart, note, 0.16, env, 1.0 - pan, pan)
                # Two soft echoes.
                for k, g in ((1, 0.5), (2, 0.28)):
                    est = int((bt + k * beat * 0.5) * SR)
                    add_sine(L, R, est, note, 0.16 * g, env, pan, 1.0 - pan)

            # Optional percussion.
            if spec.get("drums"):
                for b in range(chord_beats):
                    bstart = int((t + b * beat) * SR)
                    if b % 2 == 0:
                        add_kick(L, R, bstart)
                    else:
                        add_noise(
                            L, R, bstart, pluck_env(int(0.05 * SR), 0.03),
                            0.10, spec["seed"] + b, 0.5, 0.5,
                        )
            t += chord_dur

    reverb(L, R, wet=spec.get("reverb", 0.26))
    return finalize(L, R)


def reverb(L, R, wet):
    """A small Schroeder reverb (4 combs + 2 allpass) on the mono send."""
    n = len(L)
    mono = array.array("d", bytes(8 * n))
    for i in range(n):
        mono[i] = 0.5 * (L[i] + R[i])

    combs = [(1687, 0.78), (1913, 0.80), (2143, 0.82), (2371, 0.76)]
    acc = array.array("d", bytes(8 * n))
    for delay, fb in combs:
        buf = array.array("d", bytes(8 * n))
        for i in range(n):
            d = buf[i - delay] if i >= delay else 0.0
            buf[i] = mono[i] + d * fb
            acc[i] += buf[i] * 0.25

    for delay, g in ((347, 0.7), (113, 0.7)):
        out = array.array("d", bytes(8 * n))
        for i in range(n):
            d = out[i - delay] if i >= delay else 0.0
            out[i] = -g * acc[i] + d + g * (acc[i - delay] if i >= delay else 0.0)
        acc = out

    # Stereo spread: tiny inter-channel delay on the wet return.
    off = 240
    for i in range(n):
        L[i] += wet * acc[i]
        R[i] += wet * (acc[i - off] if i >= off else 0.0)


def finalize(L, R):
    """Soft-clip, peak-normalize, interleave to 16-bit LE bytes."""
    n = len(L)
    peak = 1e-9
    for i in range(n):
        L[i] = math.tanh(L[i] * 1.1)
        R[i] = math.tanh(R[i] * 1.1)
        peak = max(peak, abs(L[i]), abs(R[i]))
    g = 0.89 / peak
    out = array.array("h", bytes(2 * 2 * n))
    for i in range(n):
        out[2 * i] = int(max(-32768, min(32767, L[i] * g * 32767)))
        out[2 * i + 1] = int(max(-32768, min(32767, R[i] * g * 32767)))
    return out.tobytes()


def write_wav(path, pcm):
    import wave

    w = wave.open(path, "w")
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(SR)
    w.writeframes(pcm)
    w.close()


